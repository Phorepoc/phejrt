r"""components_phejrt -- the phejrt package's components (merged into core's registry when this repository is built:
PHOREPOC_ADAPTATIONS=<adaptations>:<phejrt>, see the pdk's tools/emitter/paths.py).

The runtime's .mmp is GENERATED by recipes/prepare.sh (recipes/j1-host.sh, j2-host.sh, j3-gen.sh: phoneME's own host build,
with our javacall port) into $PHE_J_ROOT (default $PHOREPOC_BUILD/jrt, the toolchain container's /build/jrt). The generated
sources name each other by absolute path, so prepare.sh builds at the path the container sees (it bind-mounts the build tree
at /build on the runner).

Packages only (SIS files, recipes/sis.sh): neither key is a ROM component.
  phemidp_sis   the runtime: phoneME CLDC-HI (C interpreter) + MIDP 2.1 + our javacall port, one EXE, loadable from RAM
  phejlaunch    the per-suite launcher template: the packer copies it with each application's UID3"""
import os

BUILD = os.environ.get("PHOREPOC_BUILD", "/build")
J_ROOT = os.environ.get("PHE_J_ROOT", os.path.join(BUILD, "jrt"))
_HERE = os.path.dirname(os.path.abspath(__file__))
_HDR = os.path.join(J_ROOT, "j3", "include", "phemidp_x32.h")

# phoneME is 2007 C/C++: the switches of its patched jvm.make for a current gcc (patches/0001), plus its own -fno-rtti / -fno-exceptions
_FLAGS = ["-include", _HDR, "-fpermissive", "-std=gnu++98", "-fno-strict-aliasing", "-fno-delete-null-pointer-checks",
          "-fno-lifetime-dse", "-fno-gnu-keywords", "-fno-operator-names", "-w"]

COMPONENTS = {
    "phemidp_sis": dict(mmp=os.path.join(J_ROOT, "j3", "group", "phemidp.mmp"), rom="phemidp_sis.exe", package_only=True, sis=True,
                        allow_wsd=True, static_ctors=True, rtti=False, cdriver=True, c_std="gnu89", stack=0x20000, flags=_FLAGS),
    "phejlaunch": dict(mmp=os.path.join(_HERE, "..", "os", "src", "phejlaunch", "phejlaunch.mmp"), package_only=True, sis=True),
}

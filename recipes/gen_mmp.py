"""gen_mmp -- the VM's .mmp for the Phorepoc build, from phoneME's own linux_c product build (hostgen.sh).

phoneME's makefiles compile the VM as: the merged shared sources (_MergedSrc*.cpp, which include the share/ files the
romgen run chose), the ROM image and natives table of the class library, OopMaps.cpp, and a fixed set of separately
compiled files (the OS layer of os/linux, the natives, the float support of the C interpreter). This script writes that
same set as $PM_ROOT/group/cldc_vm.mmp (paths relative to it), minus the x86 assembler stubs: on x32 (__i386__ is not
defined) the C interpreter takes the portable float path.

    python3 gen_mmp.py <PM_ROOT> <repo>
"""
import os
import sys

PM_ROOT, REPO = sys.argv[1], sys.argv[2]
SRC = os.path.join(PM_ROOT, "src", "cldc", "src")
GEN = os.path.join(PM_ROOT, "out", "linux_c", "target", "generated")
PROD = os.path.join(PM_ROOT, "out", "linux_c", "target", "product")
GROUP = os.path.join(PM_ROOT, "group")

# the separately compiled files of phoneME's linux_c product build (its Obj_Files), by directory
SEPARATE = {
    "vm/share/natives": ["BSDSocket.cpp", "KniUncommon.cpp", "PCSLSocket.cpp", "ReflectNatives.cpp"],
    "vm/share/runtime": ["HotRoutines0.cpp", "HotRoutines1.cpp", "JarFileUncommon.cpp", "OsFile.cpp", "OsMemory.cpp",
                         "jvmspi.cpp"],
    "vm/cpu/c": ["FloatSupport_c.cpp"],
    "vm/os/linux": ["Main_linux.cpp", "OS_linux.cpp", "OsFile_linux.cpp", "OsMemory_linux.cpp", "OsMisc_linux.cpp",
                    "OsSocket_linux.cpp"],
}
INCLUDES = ["vm/share/compiler", "vm/share/debugger", "vm/share/handles", "vm/share/memory", "vm/share/interpreter",
            "vm/share/isolate", "vm/share/natives", "vm/share/reflection", "vm/share/runtime", "vm/share/utilities",
            "vm/share/ROM", "vm/share/verifier", "vm/share/float", "vm/os/utilities", "vm/share/memoryprofiler",
            "vm/os/linux", "midp", "vm/cpu/c", "anilib/share", "anilib/linux"]


def rel(p):
    return os.path.relpath(p, GROUP).replace(os.sep, "/")


def main():
    os.makedirs(GROUP, exist_ok=True)
    merged = sorted(f for f in os.listdir(GEN) if f.startswith("_MergedSrc") and f.endswith(".cpp"))
    if not merged:
        raise SystemExit(f"gen_mmp: no _MergedSrc*.cpp in {GEN} (run hostgen.sh first)")
    out = ["// generated by recipes/gen_mmp.py from phoneME's linux_c product build -- do not edit",
           "TARGET          cldc_vm.exe",
           "TARGETTYPE      exe",
           "UID             0x100039CE 0xE5510A10",
           "CAPABILITY      NetworkServices ReadUserData WriteUserData UserEnvironment LocalServices",
           "VENDORID        0",
           "EPOCSTACKSIZE   0x10000",
           "EPOCHEAPSIZE    0x10000 0x4000000",
           ""]
    for d, files in SEPARATE.items():
        out.append("SOURCEPATH      " + rel(os.path.join(SRC, d)))
        out.append("SOURCE          " + " ".join(files))
    out.append("SOURCEPATH      " + rel(GEN))
    out.append("SOURCE          " + " ".join(merged + ["NativesTable.cpp", "ROMImage.cpp"]))
    out.append("SOURCEPATH      " + rel(PROD))
    out.append("SOURCE          OopMaps.cpp")
    out.append("")
    out.append("USERINCLUDE     " + rel(GEN))
    for d in INCLUDES:
        out.append("USERINCLUDE     " + rel(os.path.join(SRC, d)))
    out += ["",
            "OS_LAYER_SYSTEMINCLUDE_SYMBIAN",
            "OS_LAYER_LIBC_SYSTEMINCLUDE",
            "",
            "STATICLIBRARY   libcrt0.lib",
            "LIBRARY         euser.lib libc.lib libm.lib libpthread.lib libdl.lib",
            ""]
    with open(os.path.join(GROUP, "cldc_vm.mmp"), "w", newline="\n") as f:
        f.write("#include <platform_paths.hrh>\n" + "\n".join(out))
    print("gen_mmp: " + os.path.join(GROUP, "cldc_vm.mmp"))


main()

"""gen_font -- javacall/phehost/midp/font_data.c: three monospaced bitmap fonts (ASCII, Latin-1, Greek, Cyrillic; bold by double
strike) for the headless display, rendered once from DejaVu Sans Mono (Bitstream Vera licence: free to embed, notice kept in the
generated file) with Pillow, no anti-aliasing.

    python3 gen_font.py <DejaVuSansMono.ttf> <out font_data.c>
"""
import sys
from PIL import Image, ImageDraw, ImageFont

TTF, OUT = sys.argv[1:3]
SETS = [("small", 10, 6, 10), ("medium", 12, 7, 13), ("large", 17, 10, 18)]   # name, em px, cell width, cell height
RANGES = [(32, 126), (160, 255), (0x391, 0x3C9), (0x401, 0x45F)]              # first, last code point of each block
CODES = [c for a, b in RANGES for c in range(a, b + 1)]
lines = ["/* generated by recipes/gen_font.py from DejaVu Sans Mono -- do not edit.",
         " * Glyph bitmaps rendered from DejaVu Sans Mono: Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved. Bitstream Vera is a",
         " * trademark of Bitstream, Inc. DejaVu changes are in the public domain. Licence: LICENSES/DejaVu-fonts-LICENSE.txt */",
         "#include \"phe_font.h\"", "",
         "const unsigned short phe_ranges[PHE_NRANGES][3] = {   /* first, last, index of the first glyph */"]
idx = 0
for a, b in RANGES:
    lines.append("    { 0x%04x, 0x%04x, %d }," % (a, b, idx))
    idx += b - a + 1
lines += ["};", ""]
for name, em, cw, ch in SETS:
    font = ImageFont.truetype(TTF, em)
    asc, desc = font.getmetrics()
    top = max(0, (ch - (asc + desc)) // 2)
    lines.append("const unsigned short phe_glyph_%s[%d][%d] = {" % (name, len(CODES), ch))
    for c in CODES:
        im = Image.new("1", (cw, ch), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = "1"
        d.text((0, top), chr(c), font=font, fill=1)
        rows = []
        for y in range(ch):
            v = 0
            for x in range(cw):
                if im.getpixel((x, y)):
                    v |= 1 << (cw - 1 - x)
            rows.append("0x%03x" % v)
        lines.append("    {" + ",".join(rows) + "},  /* U+%04X */" % c)
    lines.append("};")
    lines.append("")
lines.append("const phe_font_metrics phe_fonts[3] = {")
for name, em, cw, ch in SETS:
    font = ImageFont.truetype(TTF, em)
    asc, desc = font.getmetrics()
    top = max(0, (ch - (asc + desc)) // 2)
    lines.append("    { %d, %d, %d, %d, (const unsigned short*)phe_glyph_%s }," % (cw, ch, ch - 3, 3, name))
lines.append("};")
open(OUT, "w", newline="\n").write("\n".join(lines) + "\n")
print(len(CODES), "glyphs per size")

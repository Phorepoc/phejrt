"""gen_font -- javacall/phehost/midp/font_data.c: three monospaced bitmap fonts (ASCII 32..126, plus bold by double strike) for the
headless display, rendered once from DejaVu Sans Mono (Bitstream Vera licence: free to embed) with Pillow, no anti-aliasing.

    python3 gen_font.py <DejaVuSansMono.ttf> <out font_data.c>
"""
import sys
from PIL import Image, ImageDraw, ImageFont

TTF, OUT = sys.argv[1:3]
SETS = [("small", 10, 6, 10), ("medium", 12, 7, 13), ("large", 17, 10, 18)]   # name, em px, cell width, cell height
lines = ["/* generated by recipes/gen_font.py from DejaVu Sans Mono -- do not edit */", "#include \"phe_font.h\"", ""]
for name, em, cw, ch in SETS:
    font = ImageFont.truetype(TTF, em)
    asc, desc = font.getmetrics()
    top = max(0, (ch - (asc + desc)) // 2)
    lines.append("const unsigned short phe_glyph_%s[95][%d] = {" % (name, ch))
    for c in range(32, 127):
        im = Image.new("1", (cw, ch), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = "1"
        d.text((0, top), chr(c), font=font, fill=1)
        rows = []
        for y in range(ch):
            v = 0
            for x in range(cw):
                if im.getpixel((x, y)):
                    v |= 1 << (cw - 1 - x)
            rows.append("0x%03x" % v)
        lines.append("    {" + ",".join(rows) + "},  /* '" + (chr(c) if chr(c) not in "\\'" else "\\" + chr(c)) + "' */")
    lines.append("};")
    lines.append("")
    print(name, "asc", asc + top, "desc", ch - asc - top)
lines.append("const phe_font_metrics phe_fonts[3] = {")
for name, em, cw, ch in SETS:
    font = ImageFont.truetype(TTF, em)
    asc, desc = font.getmetrics()
    top = max(0, (ch - (asc + desc)) // 2)
    lines.append("    { %d, %d, %d, %d, (const unsigned short*)phe_glyph_%s }," % (cw, ch, asc + top, ch - asc - top, name))
lines.append("};")
open(OUT, "w", newline="\n").write("\n".join(lines) + "\n")
